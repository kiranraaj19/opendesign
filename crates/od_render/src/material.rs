//! A basic PBR-ish material for a shaded surface: a base colour tint, plus
//! an optional diffuse/base-color texture. Everything here is plain CPU
//! data (pixels in a `Vec<u8>`); [`crate::gpu::Renderer`] is what actually
//! uploads a [`TextureImage`] to the GPU, caching by its `id` so the same
//! fabric's texture isn't re-uploaded every frame.

use std::sync::Arc;

use crate::scene::Color;

/// An RGBA8 image, straight (non-premultiplied) sRGB bytes — the usual way
/// a texture is authored. `id` is a stable identity for the renderer's
/// texture cache: two [`TextureImage`]s with the same `id` are assumed to
/// be the same pixels, so generate it once per distinct texture (e.g. per
/// fabric) and reuse it, rather than minting a fresh one every frame.
#[derive(Debug, Clone, PartialEq)]
pub struct TextureImage {
    pub id: u64,
    pub width: u32,
    pub height: u32,
    /// `width * height * 4` bytes, row-major, top to bottom.
    pub rgba: Vec<u8>,
}

/// A surface's appearance: a tint, and optionally a texture sampled
/// alongside it (the fragment shader multiplies the two, so a `None`
/// texture is the same as a solid white one).
#[derive(Debug, Clone, PartialEq)]
pub struct Material {
    /// Linear-light RGBA, as in [`crate::scene::Color`] elsewhere.
    pub base_color: Color,
    pub texture: Option<Arc<TextureImage>>,
}

impl Material {
    /// A flat tint, no texture.
    pub fn flat(base_color: Color) -> Self {
        Self {
            base_color,
            texture: None,
        }
    }

    pub fn textured(base_color: Color, texture: Arc<TextureImage>) -> Self {
        Self {
            base_color,
            texture: Some(texture),
        }
    }
}

/// A small procedural plain weave: alternating light/dark threads in a
/// checker, like the over-under of woven yarn. Generated by code rather
/// than loaded from a file, same as the procedural avatars.
pub fn plain_weave(id: u64, base: [u8; 3], tile_px: u32) -> TextureImage {
    checker_texture(id, base, tile_px, 0.12)
}

/// A coarser diagonal twill weave (denim's look): the same idea as
/// [`plain_weave`] but with the light/dark bands offset by row, so they
/// run diagonally instead of in a checkerboard.
pub fn twill_weave(id: u64, base: [u8; 3], tile_px: u32) -> TextureImage {
    let size = (tile_px * 8).max(8);
    let mut rgba = vec![0u8; (size * size * 4) as usize];
    for y in 0..size {
        for x in 0..size {
            // Diagonal bands: shift each row by one more pixel than the last.
            let band = ((x + y) / tile_px.max(1)) % 2;
            let factor = if band == 0 { 1.0 } else { 0.82 };
            let i = ((y * size + x) * 4) as usize;
            for c in 0..3 {
                rgba[i + c] = (f32::from(base[c]) * factor).clamp(0.0, 255.0) as u8;
            }
            rgba[i + 3] = 255;
        }
    }
    TextureImage {
        id,
        width: size,
        height: size,
        rgba,
    }
}

fn checker_texture(id: u64, base: [u8; 3], tile_px: u32, contrast: f32) -> TextureImage {
    let tile_px = tile_px.max(1);
    let size = tile_px * 8;
    let mut rgba = vec![0u8; (size * size * 4) as usize];
    for y in 0..size {
        for x in 0..size {
            let checker = (x / tile_px + y / tile_px) % 2;
            let factor = if checker == 0 {
                1.0 + contrast
            } else {
                1.0 - contrast
            };
            let i = ((y * size + x) * 4) as usize;
            for c in 0..3 {
                rgba[i + c] = (f32::from(base[c]) * factor).clamp(0.0, 255.0) as u8;
            }
            rgba[i + 3] = 255;
        }
    }
    TextureImage {
        id,
        width: size,
        height: size,
        rgba,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn flat_material_has_no_texture() {
        let m = Material::flat([0.5, 0.5, 0.5, 1.0]);
        assert!(m.texture.is_none());
    }

    #[test]
    fn plain_weave_alternates_light_and_dark() {
        let tex = plain_weave(1, [200, 190, 170], 4);
        assert_eq!(tex.width, 32);
        assert_eq!(tex.height, 32);
        assert_eq!(tex.rgba.len(), (32 * 32 * 4) as usize);
        // Top-left tile and its neighbour should differ.
        let a = &tex.rgba[0..3];
        let b_index = (4 * 4) as usize; // one tile across
        let b = &tex.rgba[b_index..b_index + 3];
        assert_ne!(a, b);
        // Every pixel is opaque.
        assert!(tex.rgba.chunks_exact(4).all(|p| p[3] == 255));
    }

    #[test]
    fn twill_weave_runs_diagonally() {
        let tex = twill_weave(2, [80, 90, 130], 4);
        assert_eq!(tex.width, tex.height);
        // Moving diagonally by one tile should land on the same band as the
        // origin (same colour); moving across only should differ.
        let at = |x: u32, y: u32| {
            let i = ((y * tex.width + x) * 4) as usize;
            tex.rgba[i..i + 3].to_vec()
        };
        assert_eq!(at(0, 0), at(4, 4));
        assert_ne!(at(0, 0), at(4, 0));
    }
}
